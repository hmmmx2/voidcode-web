/**
 * Refresh this repository's copies of the things the application owns.
 *
 * Usage:
 *   node scripts/sync-from-app.mjs ../VOIDCODE
 *
 * ── WHY THE CONSUMER PULLS ───────────────────────────────────────────────────────────────────────
 *
 * While this site was inside the monorepo, `scripts/sync_web_legal.py` PUSHED: it read the
 * application's legal documents and wrote them into `apps/web`. That direction stops working the
 * moment the two are separate repositories — the monorepo has nowhere to write to, and a script
 * that writes into a sibling checkout by guessing its path is worse than no script.
 *
 * So the consumer pulls, and is told where from. This repository is the one that knows it has
 * copies; the application should not have to know this repository exists.
 *
 * ── WHAT IS COPIED, AND WHY EACH IS A COPY AT ALL ────────────────────────────────────────────────
 *
 *   * The two legal documents. The original is the application's, because that is where a person
 *     clicks "I agree" and where registration records which version was accepted. Both places must
 *     publish them: the app ships them inside the binary so they work offline, and Stripe, the app
 *     stores and anyone deciding whether to install need a public URL.
 *   * Their SHA-256 digests, so `check-legal-digest.mjs` can verify the copy without reading the
 *     application's tree.
 *   * The credit-pack contract, so `check-pricing.mjs` can verify the pricing page against the
 *     prices the webhook actually grants.
 *
 * ── THE TRANSFORMATION IS PART OF THE COPY ───────────────────────────────────────────────────────
 *
 * The application's document links to its Settings screen, which does not exist here, so the
 * breadcrumb is rewritten to the site root. That difference is deliberately OUTSIDE the range the
 * digest covers — the digest is over the `SECTIONS` array only — which is what lets two files that
 * are not byte-identical still verify as the same document.
 *
 * ── WHAT THIS CANNOT DO ──────────────────────────────────────────────────────────────────────────
 *
 * Tell you that it needs running. If a price or a document changes in the application and nobody
 * runs this, every check here passes and the site publishes the old version. That is the one
 * residual risk of two repositories, and it is handled by procedure rather than by a test: the
 * application's own CI fails when its digest and its text disagree, which is the moment somebody
 * learns a copy needs refreshing.
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const app = resolve(process.argv[2] ?? "");

if (process.argv[2] === undefined) {
  console.error("usage: node scripts/sync-from-app.mjs <path-to-voidcode-checkout>");
  console.error("");
  console.error("No default, on purpose: a guessed path would silently copy from the wrong tree,");
  console.error("and the failure would be a legal document or a price that is quietly out of date.");
  process.exit(2);
}

const DOCUMENTS = ["PrivacyClient.tsx", "TermsClient.tsx"];
const APP_LEGAL = join(app, "desktop/renderer/src/components/Legal");
const APP_SHARED = join(app, "desktop/src/shared/legal.ts");
const APP_PACKS = join(app, "contracts/credit-packs.json");
const APP_DEMO = join(app, "contracts/demo-snippet.json");

for (const [what, path] of [
  ["the application's legal documents", APP_LEGAL],
  ["the application's shared legal constants", APP_SHARED],
  ["the credit-pack contract", APP_PACKS],
  ["the demo-snippet contract", APP_DEMO],
]) {
  if (!existsSync(path)) {
    console.error(`Cannot find ${what} at ${path}`);
    console.error(`Is ${app} a VOIDCODE checkout?`);
    process.exit(1);
  }
}

const HEADER = `/**
 * ── A COPY, AND THE COPY IS THE POINT ─────────────────────────────────────────────────────────────
 *
 * This file is \`desktop/renderer/src/components/Legal/{name}\` from the VoidCode application, with
 * one change: the breadcrumb points at this site's root rather than at the application's Settings
 * screen, which does not exist here.
 *
 * WHY IT IS DUPLICATED AT ALL. Both places must publish it. The application shows it in its
 * sign-up dialog, where a person accepts it — so it has to ship inside the binary and work
 * offline. Stripe and the app stores need a public URL, and a reader deciding whether to install
 * anything wants to read the terms first — so it has to be a web page. Neither can import from the
 * other: they are separate repositories.
 *
 * DO NOT EDIT THIS FILE. Edit the application's, bump its digest, then run
 * \`node scripts/sync-from-app.mjs <path-to-voidcode-checkout>\`. \`npm run verify:legal\` refuses to
 * build if this copy and that digest disagree.
 */
`;

const OLD_CRUMB = `          <Link
            href="/profile"
            className="text-[11px] text-ink-3/60 hover:text-ink-2 transition-colors"
          >
            Settings
          </Link>`;
const NEW_CRUMB = `          <Link
            href="/"
            className="text-[11px] text-ink-3/60 hover:text-ink-2 transition-colors"
          >
            VoidCode
          </Link>`;

for (const name of DOCUMENTS) {
  let source = readFileSync(join(APP_LEGAL, name), "utf8").replace(/\r\n/g, "\n");

  const crumbs = source.split(OLD_CRUMB).length - 1;
  if (crumbs !== 1) {
    console.error(`${name}: found ${crumbs} Settings breadcrumbs, expected exactly 1.`);
    console.error("The application's markup has changed; update OLD_CRUMB in this script.");
    process.exit(1);
  }
  source = source.replace(OLD_CRUMB, NEW_CRUMB);

  const marker = '"use client";\n\n';
  if (!source.startsWith(marker)) {
    console.error(`${name}: no leading "use client" directive to insert the header after.`);
    process.exit(1);
  }
  source = marker + HEADER.replace("{name}", name) + "\n" + source.slice(marker.length);

  writeFileSync(join(root, "src/components/Legal", name), source, "utf8");
  console.log(`  ${name}`);
}

// The digests, copied out of the application's shared module rather than recomputed here: a digest
// computed from the files just written would be a checksum of this script's own output.
const shared = readFileSync(APP_SHARED, "utf8");
const pick = (name, pattern) => {
  const found = pattern.exec(shared);
  if (found === null) {
    console.error(`${name} is not declared in ${APP_SHARED}`);
    process.exit(1);
  }
  return found[1];
};

const constants = `/**
 * GENERATED by \`scripts/sync-from-app.mjs\`. Do not edit.
 *
 * The numbers are COPIED from the application's \`desktop/src/shared/legal.ts\`, never recomputed
 * from the files beside them: a digest computed here would be a checksum of this repository's own
 * content, which agrees with every possible text and pins nothing.
 *
 * \`src/lib/__checks__\` — that is, \`scripts/check-legal-digest.mjs\` — hashes this repository's
 * \`components/Legal/*.tsx\` and compares. It runs as \`prebuild\`, so a deploy fails rather than
 * publishing a legal document that is not the one the application records consent against.
 */

/** The version registration records as accepted, and the date both documents print. */
export const TERMS_VERSION = "${pick("TERMS_VERSION", /TERMS_VERSION = "([^"]+)"/)}";
export const TERMS_DISPLAY_DATE = "${pick("TERMS_DISPLAY_DATE", /TERMS_DISPLAY_DATE = "([^"]+)"/)}";

/**
 * SHA-256 of each document's \`SECTIONS\` array: everything from \`const SECTIONS: Section[] = [\` up
 * to the \`Sub-components\` banner, with carriage returns removed.
 *
 * THE SCOPE IS NOT A DETAIL. The two copies legitimately differ outside that range — this one
 * carries the header above and a breadcrumb pointing at this site's root. A digest over the whole
 * file would differ between them by construction and could never agree.
 */
export const PRIVACY_SECTIONS_SHA256 = "${pick(
  "PRIVACY_SECTIONS_SHA256",
  /PRIVACY_SECTIONS_SHA256\s*=\s*\n?\s*"([0-9a-f]{64})"/
)}";
export const TERMS_SECTIONS_SHA256 = "${pick(
  "TERMS_SECTIONS_SHA256",
  /TERMS_SECTIONS_SHA256\s*=\s*\n?\s*"([0-9a-f]{64})"/
)}";
`;
writeFileSync(join(root, "src/lib/legal.ts"), constants, "utf8");
console.log("  src/lib/legal.ts");

copyFileSync(APP_PACKS, join(root, "src/lib/credit-packs.json"));
console.log("  src/lib/credit-packs.json");

copyFileSync(APP_DEMO, join(root, "src/lib/demo-snippet.json"));
console.log("  src/lib/demo-snippet.json");

console.log("");
console.log("Now run `npm run verify` to check the copies before committing them.");
